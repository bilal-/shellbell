// Generate local assets from unchanged upstream npm packages; no CDN or fork.

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const packageRoot = (name) => path.resolve(path.dirname(require.resolve(name)), "..");
const result = await build({
  entryPoints: [path.join(root, "src/terminal/runtime.ts")],
  bundle: true,
  write: false,
  minify: true,
  platform: "browser",
  target: "es2022",
  legalComments: "inline",
});
const script = result.outputFiles[0].text;
const css = await readFile(path.join(packageRoot("@xterm/xterm"), "css/xterm.css"), "utf8");
const font = await readFile(path.join(root, "assets/fonts/JetBrainsMonoNerdFont-Regular.ttf"));
const notices = [];
for (const name of [
  "@xterm/xterm",
  "@xterm/addon-unicode-graphemes",
  "@xterm/addon-webgl",
  "@xterm/addon-web-links",
]) {
  const dir = packageRoot(name);
  const pkg = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
  notices.push(
    `${name} ${pkg.version}\nhttps://github.com/xtermjs/xterm.js\n\n${await readFile(path.join(dir, "LICENSE"), "utf8")}`,
  );
}
notices.push(
  `JetBrains Mono Nerd Font\n\n${await readFile(path.join(root, "assets/fonts/LICENSE.md"), "utf8")}`,
);
const license = notices.join("\n\n---\n\n");
const hash = createHash("sha256").update(script).digest("base64");
// Clip virtual renderer overscan to the spacer's source geometry. Absolute
// children otherwise create scrollable blank space below a short bottom-aligned grid.
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; font-src data:; img-src data:; connect-src 'none'; base-uri 'none'; form-action 'none'"><style>${css}\n@font-face{font-family:ShellbellMono;src:url(data:font/ttf;base64,${font.toString("base64")})}html,body{margin:0;width:100%;height:100%;overflow:hidden;background:#000}#scroll{position:absolute;inset:0;overflow:auto;overscroll-behavior:contain}#spacer{position:relative;min-height:100%;overflow:hidden}#terminal{position:absolute;left:0;top:0}.xterm-viewport{overflow:hidden!important}.xterm{padding:0}.xterm-helper-textarea{pointer-events:none!important}</style></head><body><div id="scroll"><div id="spacer"><div id="terminal"></div></div></div><script>${script}</script></body></html>`;
const generated = `// Generated by scripts/build-terminal.mjs; do not edit. Upstream MIT notices included.\nexport const terminalHtml: string = ${JSON.stringify(html)};\nexport const terminalLicenses: string = ${JSON.stringify(license)};\n`;
const output = path.join(root, "src/terminal/gen/document.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== generated)
    throw new Error("Terminal assets are stale: run pnpm -F @shellbell/mobile terminal:build");
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, generated);
}
console.log(
  `Offline terminal assets ${process.argv.includes("--check") ? "verified" : "generated"} (${Buffer.byteLength(html)} bytes)`,
);
