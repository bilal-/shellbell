// Generate local assets from unchanged upstream npm packages; no CDN or fork.

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const packageRoot = (name) => path.resolve(path.dirname(require.resolve(name)), "..");
const result = await build({
  entryPoints: [path.join(root, "src/terminal/runtime.ts")],
  bundle: true,
  write: false,
  minify: true,
  platform: "browser",
  target: "es2022",
  legalComments: "inline",
});
const script = result.outputFiles[0].text;
const css = await readFile(path.join(packageRoot("@xterm/xterm"), "css/xterm.css"), "utf8");
const font = await readFile(path.join(root, "assets/fonts/JetBrainsMonoNerdFont-Regular.ttf"));
const notices = [];
for (const name of [
  "@xterm/xterm",
  "@xterm/addon-unicode-graphemes",
  "@xterm/addon-webgl",
  "@xterm/addon-web-links",
  "@xterm/addon-fit",
  "@xterm/addon-search",
  "@xterm/addon-serialize",
]) {
  const dir = packageRoot(name);
  const pkg = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
  // Serialize 0.14.0 omits LICENSE from npm. This is the exact upstream licence
  // from the source commit recorded in that archive, checked in with attribution.
  const licenseFile =
    name === "@xterm/addon-serialize" &&
    pkg.version === "0.14.0" &&
    pkg.commit === "f447274f430fd22513f6adbf9862d19524471c04"
      ? path.join(root, "assets/licenses/xterm-addon-serialize-0.14.0.LICENSE")
      : path.join(dir, "LICENSE");
  notices.push(
    `${name} ${pkg.version}\nhttps://github.com/xtermjs/xterm.js\n\n${await readFile(licenseFile, "utf8")}`,
  );
}
notices.push(
  `JetBrains Mono Nerd Font\n\n${await readFile(path.join(root, "assets/fonts/LICENSE.md"), "utf8")}`,
);
const license = notices.join("\n\n---\n\n");
const hash = createHash("sha256").update(script).digest("base64");
// xterm owns scrollback and its viewport. The outer pan accommodates a larger host grid.
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; font-src data:; img-src data:; connect-src 'none'; base-uri 'none'; form-action 'none'"><style>${css}\n@font-face{font-family:ShellbellMono;src:url(data:font/ttf;base64,${font.toString("base64")})}html,body{margin:0;width:100%;height:100%;overflow:hidden;background:#000}#container{position:absolute;inset:0;overflow:auto;overscroll-behavior:contain}#terminal{position:relative;min-width:100%;min-height:1px;touch-action:pan-x}.xterm{padding:0}.touch-select{touch-action:none}.selection-handle{position:absolute;width:44px;height:44px;padding:0;border:0;background:transparent;transform:translate(-50%,-50%);z-index:20;touch-action:none}.selection-handle::before{content:"";position:absolute;inset:8px;border:2px solid #e8e8ed;border-radius:50%;background:#2e745b;pointer-events:none}.selection-handle[hidden]{display:none}</style></head><body><div id="container"><div id="terminal"></div></div><script>${script}</script></body></html>`;
const generated = `// Generated by scripts/build-terminal.mjs; do not edit. Upstream MIT notices included.\nexport const terminalHtml: string = ${JSON.stringify(html)};\nexport const terminalLicenses: string = ${JSON.stringify(license)};\n`;
const output = path.join(root, "src/terminal/gen/document.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== generated)
    throw new Error("Terminal assets are stale: run pnpm -F @shellbell/mobile terminal:build");
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, generated);
}
console.log(
  `Offline terminal assets ${process.argv.includes("--check") ? "verified" : "generated"} (${Buffer.byteLength(html)} bytes)`,
);
